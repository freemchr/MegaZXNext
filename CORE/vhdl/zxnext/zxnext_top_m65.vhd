library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.std_logic_unsigned.all;

library unisim;
use unisim.vcomponents.all;

entity zxnext_top_m65 is
   generic (
      g_video_def       : unsigned(2 downto 0)  := "000";
      g_version         : unsigned(7 downto 0)  := X"32";
      g_sub_version     : unsigned(7 downto 0)  := X"00";
      g_video_inc       : unsigned(1 downto 0)  := "10"
   );
   port (
      g_machine_id      : in  unsigned(7 downto 0);
      g_board_issue     : in  unsigned(3 downto 0);

      -- Clocks: all generated by the same MMCM and therefore phase aligned
      CLK_28            : in  std_logic;
      CLK_28_n          : in  std_logic;                       -- CLK_28 phase shifted by 180 degrees
      CLK_14            : in  std_logic;
      CLK_7             : in  std_logic;

      HW_RESET          : in  std_logic;
      SW_RESET          : in  std_logic;

      CPU_SPEED         : out std_logic_vector(1 downto 0);
      CPU_SPEED_SW      : in  std_logic := '0';                 -- pulse: cycle through the cpu speeds
      CPU_WAIT          : in  std_logic := '0';

      RAM_A_ADDR        : out std_logic_vector(20 downto 0);   -- 2MB memory space
      RAM_A_REQ         : out std_logic;                       -- '1' indicates memory request on next rising edge
      RAM_A_RD_n        : out std_logic;                       -- '0' for read, '1' for write
      RAM_A_DI          : in  std_logic_vector(7 downto 0);    -- data read from memory
      RAM_A_DO          : out std_logic_vector(7 downto 0);    -- data written to memory

      RAM_B_ADDR        : out std_logic_vector(20 downto 0);   -- 2MB memory space
      RAM_B_REQ         : out std_logic;                       -- toggle indicates memory request
      RAM_B_DI          : in  std_logic_vector(7 downto 0);    -- data read from memory

      -- Membrane keyboard: the membrane scanner selects a row and expects the
      -- low active state of the 7 columns of that row (6:5 are the extra columns)
      membrane_row_o    : out std_logic_vector(2 downto 0);
      membrane_col_i    : in  std_logic_vector(6 downto 0);

      -- Special keys, high active: F1 .. F10 of the original ZX Next
      fn_keys_i         : in  std_logic_vector(10 downto 1);

      -- SD Card (SPI)
      sd_cs0_n_o        : out std_logic;
      sd_cs1_n_o        : out std_logic;
      sd_sclk_o         : out std_logic;
      sd_mosi_o         : out std_logic;
      sd_miso_i         : in  std_logic := '1';

      -- Joystick
      joy_left          : in  std_logic_vector(11 downto 0);   -- active high  MODE X Z Y START A C B U D L R
      joy_right         : in  std_logic_vector(11 downto 0);   -- active high  MODE X Z Y START A C B U D L R

      -- Audio
      audio_L           : out std_logic_vector(11 downto 0);
      audio_R           : out std_logic_vector(11 downto 0);

      -- K7
      ear_port_i        : in  std_logic := '1';
      mic_port_o        : out std_logic;

      -- Video (synchronized to CLK_14)
      RGB               : out std_logic_vector(8 downto 0);    -- RGB333
      RGB_VS_n          : out std_logic;
      RGB_HS_n          : out std_logic;
      RGB_VB_n          : out std_logic;
      RGB_HB_n          : out std_logic;
      RGB_NTSC          : out std_logic;
      center            : in  std_logic;

      -- I2C (RTC)
      i2c_scl_o         : out std_logic;
      i2c_sda_o         : out std_logic;
      i2c_sda_i         : in  std_logic := '1';

      uart_rx_i         : in  std_logic;
      uart_tx_o         : out std_logic;
      esp_reset_o       : out std_logic
   );
end entity zxnext_top_m65;

architecture rtl of zxnext_top_m65 is

   -- resets

   signal zxn_video_mode         : std_logic_vector(2 downto 0);
   signal actual_video_mode      : std_logic_vector(2 downto 0)   := "000";

   signal reset_counter          : std_logic_vector(9 downto 0);
   signal reset                  : std_logic;

   signal zxn_reset_hard         : std_logic;
   signal zxn_reset_soft         : std_logic;

   -- clocks

   signal CLK_i0                 : std_logic := '0';
   signal CLK_CPU                : std_logic;
   signal cpu_sel_28             : std_logic := '0';

   signal clk_28_div             : std_logic_vector(17 downto 0) := (others => '0');

   signal CLK_28_PSG_EN          : std_logic;
   signal CLK_28_JOY_EN          : std_logic;
   signal CLK_28_MEMBRANE_EN     : std_logic;

   signal zxn_clock_contend      : std_logic;
   signal zxn_clock_lsb          : std_logic;
   signal zxn_cpu_speed          : std_logic_vector(1 downto 0);
   signal zxn_cpu_speed2         : std_logic_vector(1 downto 0) := "00";
   signal cpu_speed_d            : std_logic_vector(1 downto 0) := "00";
   signal cpu_settle             : unsigned(3 downto 0) := (others => '0');

   -- serial communication

   signal zxn_i2c_scl            : std_logic;

   -- audio

   signal zxn_audio_L_pre        : std_logic_vector(12 downto 0);
   signal zxn_audio_R_pre        : std_logic_vector(12 downto 0);

   -- buttons, joystick, keyboard

   signal zxn_joy_io_mode_en     : std_logic;

   signal zxn_joy_left_type      : std_logic_vector(2 downto 0);
   signal zxn_joy_right_type     : std_logic_vector(2 downto 0);

   signal zxn_keymap_addr        : std_logic_vector(8 downto 0);
   signal zxn_keymap_dat         : std_logic_vector(7 downto 0);
   signal zxn_keymap_we          : std_logic;
   signal zxn_joymap_we          : std_logic;

   signal zxn_key_row            : std_logic_vector(7 downto 0);
   signal zxn_key_col            : std_logic_vector(4 downto 0);

   signal zxn_cancel_extended_entries  : std_logic;
   signal zxn_extended_keys      : std_logic_vector(15 downto 0);

   signal membrane_index         : std_logic_vector(2 downto 0);
   signal membrane_stick_col     : std_logic_vector(6 downto 0);
   signal membrane_cols          : std_logic_vector(6 downto 0);

   -- special keys
   signal zxn_boot               : std_logic;
   signal zxn_spkey_function     : std_logic_vector(10 downto 1);
   signal zxn_spkey_buttons      : std_logic_vector(1 downto 0);

begin

   ------------------------------------------------------------
   -- RESETS --------------------------------------------------
   ------------------------------------------------------------

   process (CLK_28)
   begin
      if rising_edge(CLK_28) then
         if zxn_video_mode /= actual_video_mode or (zxn_reset_soft or zxn_reset_hard or SW_RESET) = '1' then
            actual_video_mode <= zxn_video_mode;
            reset_counter <= (others => '1');
            reset <= '1';
         elsif reset_counter /= "0000000000" then
            reset_counter <= reset_counter - 1;
         else
            reset <= '0';
         end if;
      end if;
   end process;

   ------------------------------------------------------------
   -- CLOCKS --------------------------------------------------
   ------------------------------------------------------------

   CPU_SPEED <= zxn_cpu_speed2;

   -- CPU clock generation for 3.5 MHz (incl. contention), 7 MHz and 14 MHz.
   -- As in MiSTer, CLK_i0 is a register driven clock. Unlike MiSTer, CLK_i0 may not rise for 15
   -- CLK_28 cycles after a speed change (cpu_settle). The ZX Next sizes a memory cycle by its new
   -- speed at once (memcycle_count_max: the request goes out 7 CLK_28 cycles after MREQ at 3.5 MHz),
   -- but the cycle that straddles the switch began at the old speed: from 28 MHz, T1 and T2 run at
   -- 28 MHz and T3 comes with the first CLK_i0 edge, which can be only a few cycles later. The CPU
   -- then takes the opcode before it was requested from memory. On R6 NextZXOS lost the INC HL after
   -- its OUT to nextreg 0x07 that way, the ULA clip window got garbage and the screen went black.
   -- The stretch gives the straddling cycle at least one full 3.5 MHz T-state.
   process (CLK_28)
      variable clk_i0_v : std_logic;
   begin
      if rising_edge(CLK_28) then
         clk_i0_v := CLK_i0;
         case zxn_cpu_speed2 is
            when "00"   =>
               if clk_28_div(1 downto 0) = "00" then
                  if zxn_clock_lsb = '1' and zxn_clock_contend = '0' then
                     clk_i0_v := '0';
                  elsif zxn_clock_lsb = '0' then
                     clk_i0_v := '1';
                  end if;
               end if;

            when "01"   =>
               clk_i0_v := clk_28_div(1);

            when others =>
               clk_i0_v := clk_28_div(0);
         end case;

         cpu_speed_d <= zxn_cpu_speed;
         if zxn_cpu_speed /= cpu_speed_d then
            cpu_settle <= (others => '1');
         elsif cpu_settle /= 0 then
            cpu_settle <= cpu_settle - 1;
         end if;

         if clk_i0_v = '0' or (zxn_cpu_speed = cpu_speed_d and cpu_settle = 0) then
            CLK_i0 <= clk_i0_v;
         end if;

         if clk_28_div(1 downto 0) = "11" then
            zxn_cpu_speed2 <= zxn_cpu_speed;
         end if;

         -- 28 MHz mode: take the CPU clock directly from CLK_28. As in MiSTer (q0/q1), the select
         -- follows zxn_cpu_speed, not the delayed zxn_cpu_speed2, so the CPU leaves CLK_28 (and its
         -- 28 MHz wait state) as soon as the ZX Next changes its speed.
         cpu_sel_28 <= zxn_cpu_speed(1) and zxn_cpu_speed(0);
      end if;
   end process;

   -- Glitch-free switch-over between CLK_i0 (3.5, 7, 14 MHz) and CLK_28 (28 MHz).
   -- BUFGMUX_CTRL waits for the current clock to go low before switching.
   i_bufgmux_cpu : BUFGMUX_CTRL
      port map (
         I0 => CLK_i0,
         I1 => CLK_28,
         S  => cpu_sel_28,
         O  => CLK_CPU
      );

   -- Clock Enables
   clk_28_div <= clk_28_div + 1 when rising_edge(CLK_28);

   CLK_28_PSG_EN <= '1' when clk_28_div(3 downto 0) = "1110" else '0';                            -- AY clock enable @ 1.75MHz
   CLK_28_JOY_EN <= '1' when clk_28_div(6 downto 0) = ("111" & X"F") else '0';                    -- stick step every 4.57us
   CLK_28_MEMBRANE_EN <= '1' when clk_28_div(8 downto 7) = "11" and CLK_28_JOY_EN = '1' else '0'; -- complete scan every 2.5 scanlines

   ------------------------------------------------------------
   -- JOYSTICKS, KEYBOARD -------------------------------------
   ------------------------------------------------------------

   membrane_row_o <= membrane_index;
   membrane_cols  <= membrane_stick_col and membrane_col_i;

   -- membrane keyboard

   membrane_mod : entity work.membrane
   port map
   (
      i_CLK             => CLK_28,
      i_CLK_EN          => CLK_28_MEMBRANE_EN,

      i_reset           => reset,

      i_rows            => zxn_key_row,
      o_cols            => zxn_key_col,

      o_membrane_rows   => open,
      o_membrane_ridx   => membrane_index,
      i_membrane_cols   => membrane_cols,

      i_cancel_extended_entries => zxn_cancel_extended_entries,
      o_extended_keys   => zxn_extended_keys
   );

   -- membrane joystick (joystick to key mapping)

   membrane_stick_mod : entity work.membrane_stick
   port map
   (
      i_CLK             => CLK_28,
      i_CLK_EN          => CLK_28_MEMBRANE_EN,

      i_reset           => reset,

      i_joy_en_n        => zxn_joy_io_mode_en,

      i_joy_left        => joy_left,
      i_joy_left_type   => zxn_joy_left_type,

      i_joy_right       => joy_right,
      i_joy_right_type  => zxn_joy_right_type,

      i_membrane_row    => membrane_index,
      o_membrane_col    => membrane_stick_col,

      i_keymap_addr     => zxn_keymap_addr(4 downto 0),
      i_keymap_data     => zxn_keymap_dat(5 downto 0),
      i_keymap_we       => zxn_joymap_we
   );

   ------------------------------------------------------------
   -- SERIAL COMMUNICATION ------------------------------------
   ------------------------------------------------------------

   i2c_scl_o <= zxn_i2c_scl;

   ------------------------------------------------------------
   -- TBBLUE / ZXNEXT -----------------------------------------
   ------------------------------------------------------------

   --  F1 = hard reset
   --  F3 = toggle 50Hz / 60Hz display
   --  F4 = soft reset
   --  F8 = change cpu speed
   --  F9 = m1 button (multiface nmi)
   -- F10 = drive button (divmmc nmi)

   zxn_boot           <= fn_keys_i(1) or HW_RESET;
   zxn_spkey_function <= fn_keys_i(10) & fn_keys_i(9) & (fn_keys_i(8) or CPU_SPEED_SW) & "000" & (fn_keys_i(4) or fn_keys_i(1) or HW_RESET) & fn_keys_i(3) & "00";
   zxn_spkey_buttons  <= fn_keys_i(10) & fn_keys_i(9);

   zxnext : entity work.zxnext
   generic map
   (
      g_video_def          => g_video_def,
      g_version            => g_version,
      g_sub_version        => g_sub_version,
      g_video_inc          => g_video_inc
   )
   port map
   (
      g_machine_id         => g_machine_id,
      g_board_issue        => g_board_issue,

      -- CLOCK

      i_CLK_28             => CLK_28,
      i_CLK_28_n           => CLK_28_n,
      i_CLK_14             => CLK_14,
      i_CLK_7              => CLK_7,
      i_CLK_CPU            => CLK_CPU,
      i_CLK_PSG_EN         => CLK_28_PSG_EN,

      o_CPU_SPEED          => zxn_cpu_speed,
      o_CPU_CONTEND        => zxn_clock_contend,
      o_CPU_CLK_LSB        => zxn_clock_lsb,
      i_CPU_WAIT           => CPU_WAIT,

      -- RESET

      i_RESET              => reset,
      i_BOOT               => zxn_boot,
      o_RESET_PERIPHERAL   => esp_reset_o,

      o_RESET_HARD         => zxn_reset_hard,
      o_RESET_SOFT         => zxn_reset_soft,

      -- SPECIAL KEYS

      i_SPKEY_FUNCTION     => zxn_spkey_function,
      i_SPKEY_BUTTONS      => zxn_spkey_buttons,

      -- MEMBRANE KEYBOARD

      o_KBD_CANCEL         => zxn_cancel_extended_entries,
      o_KBD_ROW            => zxn_key_row,
      i_KBD_COL            => zxn_key_col,
      i_KBD_EXTENDED_KEYS  => zxn_extended_keys,

      -- PS/2 KEYBOARD AND KEY JOYSTICK SETUP

      o_KEYMAP_ADDR        => zxn_keymap_addr,
      o_KEYMAP_DATA        => zxn_keymap_dat,
      o_KEYMAP_WE          => zxn_keymap_we,
      o_JOYMAP_WE          => zxn_joymap_we,

      -- JOYSTICK

      i_JOY_LEFT           => joy_left,
      i_JOY_RIGHT          => joy_right,
      o_JOY_IO_MODE_EN     => zxn_joy_io_mode_en,
      o_JOY_LEFT_TYPE      => zxn_joy_left_type,
      o_JOY_RIGHT_TYPE     => zxn_joy_right_type,

      -- MOUSE (not supported on the MEGA65 port, yet)

      i_MOUSE_X            => (others => '0'),
      i_MOUSE_Y            => (others => '0'),
      i_MOUSE_BUTTON       => (others => '0'),
      i_MOUSE_WHEEL        => (others => '0'),
      o_MOUSE_CONTROL      => open,

      -- I2C

      i_I2C_SCL_n          => zxn_i2c_scl,
      i_I2C_SDA_n          => i2c_sda_i,
      o_I2C_SCL_n          => zxn_i2c_scl,
      o_I2C_SDA_n          => i2c_sda_o,

      -- SPI

      o_SPI_SS_SD1_n       => sd_cs1_n_o,
      o_SPI_SS_SD0_n       => sd_cs0_n_o,
      o_SPI_SCK            => sd_sclk_o,
      o_SPI_MOSI           => sd_mosi_o,
      i_SPI_SD_MISO        => sd_miso_i,
      i_SPI_FLASH_MISO     => '1',

      -- UART

      i_UART0_RX           => uart_rx_i,
      o_UART0_TX           => uart_tx_o,
      i_UART0_CTS_n        => '0',
      o_UART0_RTR_n        => open,

      -- VIDEO (synchronized to i_CLK_14)

      o_RGB                => RGB,
      o_RGB_VS_n           => RGB_VS_n,
      o_RGB_HS_n           => RGB_HS_n,
      o_RGB_VB_n           => RGB_VB_n,
      o_RGB_HB_n           => RGB_HB_n,
      o_VIDEO_MODE         => zxn_video_mode,
      o_VIDEO_50_60        => RGB_NTSC,
      center               => center,

      -- AUDIO

      i_AUDIO_EAR          => ear_port_i,
      o_AUDIO_MIC          => mic_port_o,
      o_AUDIO_L            => zxn_audio_L_pre,
      o_AUDIO_R            => zxn_audio_R_pre,

      -- EXTERNAL SRAM (synchronized to i_CLK_28)

      o_RAM_A_ADDR         => RAM_A_ADDR,
      o_RAM_A_REQ          => RAM_A_REQ,
      o_RAM_A_RD_n         => RAM_A_RD_n,
      i_RAM_A_DI           => RAM_A_DI,
      o_RAM_A_DO           => RAM_A_DO,
      o_RAM_B_ADDR         => RAM_B_ADDR,
      o_RAM_B_REQ_T        => RAM_B_REQ,
      i_RAM_B_DI           => RAM_B_DI,

      -- EXPANSION BUS

      i_BUS_DI             => (others => '1'),
      i_BUS_WAIT_n         => '1',
      i_BUS_NMI_n          => '1',
      i_BUS_INT_n          => '1',
      i_BUS_BUSREQ_n       => '1',
      i_BUS_ROMCS_n        => '1',
      i_BUS_IORQULA_n      => '1',

      -- ESP GPIO

      i_ESP_GPIO_20        => (others => '1'),
      o_ESP_GPIO_0         => open,
      o_ESP_GPIO_0_EN      => open,

      -- PI GPIO

      i_GPIO               => (others => '1'),
      o_GPIO               => open,
      o_GPIO_EN            => open
   );

   -- saturate the 13-bit mixer output to 12 bits
   audio_L <= (others => '1') when zxn_audio_L_pre(12) = '1' else zxn_audio_L_pre(11 downto 0);
   audio_R <= (others => '1') when zxn_audio_R_pre(12) = '1' else zxn_audio_R_pre(11 downto 0);

end architecture rtl;
