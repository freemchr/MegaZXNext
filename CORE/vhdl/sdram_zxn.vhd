----------------------------------------------------------------------------------
-- ZX Spectrum Next for MEGA65 (MegaZXNext)
--
-- SDRAM controller for the ZX Next's two memory ports on the MEGA65's
-- IS42S16320F-6BL (R4, R5 and R6 boards).
--
-- This is a VHDL translation of ZXNext_MiSTer/rtl/mister/sdram.sv
-- (Copyright (C) 2021 Alexey Melnikov, GPL v2 or later). The access manager
-- (32-bit read cache per port, CPU wait generation, opportunistic refresh,
-- Layer 2 toggle port) works like the original. The changes are:
--
--    * 112 MHz with CAS latency 3 (the -6 speed grade supports CL2 only up to
--      100 MHz) and tRCD = 3 cycles (2 cycles @ 112 MHz = 17.9 ns < 18 ns).
--    * Overlapped access cycle: a new ACTIVE is issued every 8 cycles (71 ns,
--      limited by tRC and tRAS + tRP with auto precharge). The read data is
--      delivered through a small pipeline, so that the next command does not
--      have to wait for the data of the previous one.
--    * All SDRAM outputs and the DQ input are registered in the IOBs and the
--      SDRAM clock is the inverted controller clock generated by an ODDR. This
--      is the I/O scheme of MJoergen's SDRAM controller for the MEGA65
--      (https://github.com/MJoergen/SDRAM) which is proven on real hardware.
--      Read data is sampled CL+1 cycles after the READ command, i.e. in the
--      middle of the data valid window.
--    * 100 us power-up wait and ten auto refresh cycles during initialization.
--    * DQ is split into dq_out / dq_oe_n / dq_in; the tri-state buffers are
--      inferred in the top level file.
--    * Layer 2 slot reservation: Port B has no wait signal. Layer 2 toggles a
--      request and latches the result of the previous request every 4 cycles
--      of CLK_28 (= 16 cycles of this controller = 142.9 ns). In the 320x256
--      and 640x256 modes the memory is organized in columns, so every request
--      is a miss. The controller learns the phase of the Layer 2 requests and
--      does not start other accesses in the two cycles before an expected
--      Layer 2 request. A Layer 2 miss is therefore served within ~107 ns.
--    * Port B cache coherency: a Port B hit is only possible after the cache
--      line has been completely filled, and CPU writes invalidate a matching
--      Port B cache line (the MiSTer version has small stale data windows).
--    * Port A is only evaluated, and its outputs only change, on the cycles of
--      this clock that coincide with an edge (rising or falling) of CLK_28.
--      The Port A inputs come from the ZX Next's combinatorial memory decoding
--      (DivMMC, MMU, ...), launched by either edge of CLK_28 or the CPU clock,
--      and need up to 2 cycles of this clock to settle; in the cycle in between
--      they can show garbage. The CPU samples ram_a_wait / ram_a_do on either
--      edge of its clock with paths of up to 2 cycles. The multicycle paths in
--      CORE.xdc describe exactly this. clk_28_i is only used as phase reference.
--
-- clk_i must be 4x the ZX Next's 28 MHz clock and phase aligned with it
-- (both come from the same MMCM). RAM_A_* and RAM_B_* belong to the 28 MHz
-- (resp. CPU clock) domain; see CORE.xdc for the multicycle constraints.
--
-- MEGA65 port done by Chris Freeman in 2026 and licensed under GPL v3
----------------------------------------------------------------------------------

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library unisim;
use unisim.vcomponents.all;

entity sdram_zxn is
   port (
      clk_i          : in  std_logic;                        -- 112 MHz
      rst_i          : in  std_logic;                        -- synchronous reset: (re-)initializes the SDRAM
      clk_28_i       : in  std_logic;                        -- ZX Next 28 MHz clock (phase reference)

      -- ZX Next port A: CPU / DMA (byte addresses)
      ram_a_addr_i   : in  std_logic_vector(20 downto 0);
      ram_a_req_i    : in  std_logic;                        -- rising edge starts an access
      ram_a_rd_n_i   : in  std_logic;                        -- '0' = read, '1' = write
      ram_a_di_i     : in  std_logic_vector(7 downto 0);     -- data to be written
      ram_a_do_o     : out std_logic_vector(7 downto 0);     -- data read
      ram_a_wait_o   : out std_logic;

      -- ZX Next port B: Layer 2 video fetch (read only)
      ram_b_addr_i   : in  std_logic_vector(20 downto 0);
      ram_b_req_i    : in  std_logic;                        -- toggle starts an access
      ram_b_do_o     : out std_logic_vector(7 downto 0);

      -- SDRAM device
      sdram_clk_o    : out std_logic;
      sdram_cke_o    : out std_logic;
      sdram_cs_n_o   : out std_logic;
      sdram_ras_n_o  : out std_logic;
      sdram_cas_n_o  : out std_logic;
      sdram_we_n_o   : out std_logic;
      sdram_ba_o     : out std_logic_vector(1 downto 0);
      sdram_a_o      : out std_logic_vector(12 downto 0);
      sdram_dqml_o   : out std_logic;
      sdram_dqmh_o   : out std_logic;
      sdram_dq_out_o : out std_logic_vector(15 downto 0);
      sdram_dq_oe_n_o: out std_logic_vector(15 downto 0);
      sdram_dq_in_i  : in  std_logic_vector(15 downto 0)
   );
end entity sdram_zxn;

architecture synthesis of sdram_zxn is

   constant C_CLOCK_MHZ     : natural := 112;

   constant RASCAS_DELAY    : natural := 3;         -- tRCD = 18 ns -> 3 cycles @ 112 MHz
   constant BURST_LENGTH    : std_logic_vector(2 downto 0) := "001"; -- 2 words
   constant ACCESS_TYPE     : std_logic := '0';     -- sequential
   constant CAS_LATENCY     : natural := 3;
   constant OP_MODE         : std_logic_vector(1 downto 0) := "00";
   constant NO_WRITE_BURST  : std_logic := '1';     -- single access write

   -- SDRAM mode register value (called MODE in the MiSTer version)
   constant C_MODE_REG : std_logic_vector(12 downto 0) :=
      "000" & NO_WRITE_BURST & OP_MODE & std_logic_vector(to_unsigned(CAS_LATENCY, 3)) & ACCESS_TYPE & BURST_LENGTH;

   constant STATE_IDLE      : natural := 0;
   constant STATE_START     : natural := STATE_IDLE + 1;
   constant STATE_CONT      : natural := STATE_START + RASCAS_DELAY;
   constant STATE_LAST      : natural := STATE_START + 7;       -- next ACTIVE 8 cycles after the previous one
   constant C_DELIVER       : natural := CAS_LATENCY + 2;       -- data delivery: cycles after the READ command

   constant MODE_NORMAL     : std_logic_vector(1 downto 0) := "00";
   constant MODE_RESET      : std_logic_vector(1 downto 0) := "01";
   constant MODE_LDM        : std_logic_vector(1 downto 0) := "10";
   constant MODE_PRE        : std_logic_vector(1 downto 0) := "11";

   -- RAS# CAS# WE#
   constant CMD_NOP         : std_logic_vector(2 downto 0) := "111";
   constant CMD_ACTIVE      : std_logic_vector(2 downto 0) := "011";
   constant CMD_READ        : std_logic_vector(2 downto 0) := "101";
   constant CMD_WRITE       : std_logic_vector(2 downto 0) := "100";
   constant CMD_PRECHARGE   : std_logic_vector(2 downto 0) := "010";
   constant CMD_AUTO_REFRESH: std_logic_vector(2 downto 0) := "001";
   constant CMD_LOAD_MODE   : std_logic_vector(2 downto 0) := "000";

   -- 100 us power-up delay (plus some margin)
   constant C_POR_CYCLES    : natural := 105 * C_CLOCK_MHZ;

   -- channel 0: port A (CPU), channel 1: port B (Layer 2)
   type last_a_t    is array (0 to 1) of std_logic_vector(21 downto 2);
   type last_data_t is array (0 to 1) of std_logic_vector(31 downto 0);

   signal state      : natural range 0 to STATE_LAST := STATE_IDLE;
   signal a          : std_logic_vector(22 downto 0) := (others => '0');
   signal bank       : std_logic_vector(1 downto 0)  := (others => '0');
   signal data       : std_logic_vector(15 downto 0) := (others => '0');
   signal we         : std_logic := '0';
   signal ram_req    : std_logic := '0';
   signal last_a     : last_a_t := (others => (others => '1'));
   signal last_data  : last_data_t := (others => (others => '0'));
   signal rfsh_cnt   : unsigned(8 downto 0) := (others => '0');

   -- Phase of CLK_28: ph = number of this clock's edge within a CLK_28 cycle (0 = rising edge
   -- of CLK_28, 2 = falling edge). Port A is only evaluated on the even edges.
   signal t28        : std_logic := '0';                          -- toggles with CLK_28
   signal t28_s      : std_logic := '0';
   signal t28_d      : std_logic := '0';
   signal ph         : unsigned(1 downto 0) := (others => '0');

   -- Port A request, latched on the even edge where it is seen first
   signal a_req_e    : std_logic := '0';                          -- ram_a_req_i at the previous even edge
   signal a_addr_r   : std_logic_vector(20 downto 0) := (others => '0');
   signal a_rd_n_r   : std_logic := '1';
   signal a_di_r     : std_logic_vector(7 downto 0) := (others => '0');
   signal a_fetch_r  : std_logic := '0';
   signal old_b_req  : std_logic := '0';
   signal ch0_busy   : std_logic := '0';                          -- the access being started is for channel 0
   signal ch1_busy   : std_logic := '0';                          -- the access being started is for channel 1
   -- A request that arrives while port A is busy (at 28 MHz the ZX Next does not wait on writes,
   -- so the next request can follow before the write has been served): it is served next
   signal a_queued   : std_logic := '0';
   signal a_q_addr   : std_logic_vector(20 downto 0) := (others => '0');
   signal a_q_rd_n   : std_logic := '1';
   signal a_q_di     : std_logic_vector(7 downto 0) := (others => '0');
   signal a_inflight : std_logic := '0';                          -- a port A access is in flight
   signal ch1_fill   : std_logic := '0';                          -- channel 1 cache line is being filled
   signal store      : std_logic_vector(2 downto 0) := (others => '0'); -- valid & channel & half

   -- delivery pipeline (latched with the READ/WRITE command)
   signal dl_cnt     : natural range 0 to C_DELIVER := 0;
   signal dl_ch0     : std_logic := '0';
   signal dl_ch1     : std_logic := '0';
   signal dl_req     : std_logic := '0';
   signal dl_we      : std_logic := '0';
   signal dl_a       : std_logic_vector(1 downto 0) := (others => '0');
   signal dl_data    : std_logic_vector(7 downto 0) := (others => '0');

   -- Layer 2 slot reservation
   signal cyc        : unsigned(3 downto 0) := (others => '0');   -- 16 cycles = 4 cycles of CLK_28
   signal b_seen     : std_logic := '0';
   signal l2_phase   : unsigned(3 downto 0) := (others => '0');
   signal l2_timer   : natural range 0 to 63 := 0;

   signal ram_a_do   : std_logic_vector(7 downto 0) := (others => '0');
   signal ram_a_wait : std_logic := '0';                          -- a port A access is pending
   signal a_do_o     : std_logic_vector(7 downto 0) := (others => '0');  -- copies that only change on even edges
   signal a_wait_o   : std_logic := '0';
   signal ram_b_do   : std_logic_vector(7 downto 0) := (others => '0');

   signal mode       : std_logic_vector(1 downto 0) := MODE_RESET;
   signal init_cnt   : unsigned(4 downto 0) := (others => '1');
   signal por_cnt    : natural range 0 to C_POR_CYCLES := C_POR_CYCLES;

   signal a_fetch    : std_logic;

   -- IOB registers
   signal data_reg   : std_logic_vector(15 downto 0) := (others => '0');
   signal cmd        : std_logic_vector(2 downto 0)  := CMD_NOP;
   signal sd_a       : std_logic_vector(12 downto 0) := (others => '0');
   signal sd_ba      : std_logic_vector(1 downto 0)  := (others => '0');
   signal sd_dqml    : std_logic := '0';
   signal sd_dqmh    : std_logic := '0';
   signal dq_out     : std_logic_vector(15 downto 0) := (others => '0');
   signal dq_oe_n    : std_logic_vector(15 downto 0) := (others => '1');

   attribute IOB : string;
   attribute IOB of data_reg : signal is "TRUE";
   attribute IOB of cmd      : signal is "TRUE";
   attribute IOB of sd_a     : signal is "TRUE";
   attribute IOB of sd_ba    : signal is "TRUE";
   attribute IOB of sd_dqml  : signal is "TRUE";
   attribute IOB of sd_dqmh  : signal is "TRUE";
   attribute IOB of dq_out   : signal is "TRUE";
   attribute IOB of dq_oe_n  : signal is "TRUE";

   -- keep one output enable flip-flop per DQ bit, so that each can go into its IOB
   attribute dont_touch : string;
   attribute dont_touch of dq_oe_n : signal is "true";

   function byte_sel(d : std_logic_vector(31 downto 0); sel : std_logic_vector(1 downto 0)) return std_logic_vector is
   begin
      case sel is
         when "00"   => return d( 7 downto  0);
         when "01"   => return d(15 downto  8);
         when "10"   => return d(23 downto 16);
         when others => return d(31 downto 24);
      end case;
   end function byte_sel;

begin

   ram_a_do_o   <= a_do_o;
   ram_a_wait_o <= a_wait_o;
   ram_b_do_o   <= ram_b_do;

   -- straight from the inputs: only valid on the even edges
   a_fetch <= '1' when ram_a_rd_n_i = '1' or last_a(0) /= ('0' & ram_a_addr_i(20 downto 2)) else '0';

   phase_ref : process (clk_28_i)
   begin
      if rising_edge(clk_28_i) then
         t28 <= not t28;
      end if;
   end process phase_ref;

   ---------------------------------------------------------------------------------------
   -- Access manager
   ---------------------------------------------------------------------------------------

   access_manager : process (clk_i)
      variable ch      : natural range 0 to 1;
      variable b_new   : std_logic;
      variable b_wa    : std_logic_vector(21 downto 2);
      variable a_wa    : std_logic_vector(21 downto 2);
      variable b_hit   : boolean;
      variable b_block : boolean;
      variable even    : boolean;
      variable v_wait  : std_logic;
      variable v_do    : std_logic_vector(7 downto 0);
      variable v_queue : boolean;
      variable v_qaddr : std_logic_vector(20 downto 0);
      variable v_qrd_n : std_logic;
      variable v_qdi   : std_logic_vector(7 downto 0);
   begin
      if rising_edge(clk_i) then
         data_reg <= sdram_dq_in_i;

         -- next values of ram_a_wait / ram_a_do
         v_wait  := ram_a_wait;
         v_do    := ram_a_do;
         v_queue := a_queued = '1';
         v_qaddr := a_q_addr;
         v_qrd_n := a_q_rd_n;
         v_qdi   := a_q_di;

         ---------------------------------------------------------------------------------
         -- CLK_28 phase: t28 changes after edge 0, t28_s takes it at edge 1, t28_d at edge 2
         ---------------------------------------------------------------------------------

         t28_s <= t28;
         t28_d <= t28_s;
         if t28_s /= t28_d then
            ph <= "11";
         else
            ph <= ph + 1;
         end if;
         even := ph(0) = '0';

         if rfsh_cnt /= "111111111" then
            rfsh_cnt <= rfsh_cnt + 1;
         end if;

         ---------------------------------------------------------------------------------
         -- Layer 2 phase tracking: Layer 2 requests arrive every 16 cycles at a fixed phase
         ---------------------------------------------------------------------------------

         cyc    <= cyc + 1;
         b_seen <= ram_b_req_i;
         if (b_seen xor ram_b_req_i) = '1' then
            l2_phase <= cyc;
            l2_timer <= 63;
         elsif l2_timer /= 0 then
            l2_timer <= l2_timer - 1;
         end if;

         -- Do not start an access (other than Layer 2) in the two cycles before an expected Layer 2 request:
         -- It would delay a Layer 2 miss beyond the 16 cycles that Layer 2 waits for its data.
         b_block := l2_timer /= 0 and (l2_phase - cyc = 1 or l2_phase - cyc = 2);

         ---------------------------------------------------------------------------------
         -- Cache hits
         ---------------------------------------------------------------------------------

         if even then
            a_req_e <= ram_a_req_i;
            if a_req_e = '0' and ram_a_req_i = '1' and ram_a_wait = '1' then
               -- Port A is busy: queue the request, the CPU keeps waiting until it is served
               -- pragma translate_off
               assert a_queued = '0' report "sdram_zxn: port A request lost (queue full)" severity error;
               -- pragma translate_on
               v_queue  := true;
               v_qaddr  := ram_a_addr_i;
               v_qrd_n  := ram_a_rd_n_i;
               v_qdi    := ram_a_di_i;
               a_queued <= '1';
               a_q_addr <= ram_a_addr_i;
               a_q_rd_n <= ram_a_rd_n_i;
               a_q_di   <= ram_a_di_i;
            elsif a_req_e = '0' and ram_a_req_i = '1' then
               a_addr_r  <= ram_a_addr_i;
               a_rd_n_r  <= ram_a_rd_n_i;
               a_di_r    <= ram_a_di_i;
               a_fetch_r <= a_fetch;
               -- the cached byte (timing: does not wait for the cache compare); on a miss the CPU
               -- waits and gets the data with the end of the wait
               v_do      := byte_sel(last_data(0), ram_a_addr_i(1 downto 0));
               if rfsh_cnt(8) = '1' or a_fetch = '1' then
                  v_wait := '1';
               end if;
            end if;
         end if;

         b_new := old_b_req xor ram_b_req_i;
         b_wa  := '0' & ram_b_addr_i(20 downto 2);
         b_hit := last_a(1) = b_wa and ch1_fill = '0';

         if b_new = '1' and b_hit then
            old_b_req <= ram_b_req_i;
            ram_b_do  <= byte_sel(last_data(1), ram_b_addr_i(1 downto 0));
         end if;

         ---------------------------------------------------------------------------------
         -- Command state machine: start a new access
         ---------------------------------------------------------------------------------

         if mode /= MODE_NORMAL or state /= STATE_IDLE or init_cnt /= 0 then
            if state = STATE_LAST then
               state <= STATE_IDLE;
            else
               state <= state + 1;
            end if;
         end if;

         if (state = STATE_IDLE or state = STATE_LAST) and mode = MODE_NORMAL and init_cnt = 0 then
            ram_req  <= '0';
            we       <= '0';
            ch0_busy <= '0';
            ch1_busy <= '0';

            if b_new = '1' and not b_hit then
               -- Port B miss: highest priority
               old_b_req <= ram_b_req_i;
               bank      <= "00";
               a         <= "00" & ram_b_addr_i;
               ram_req   <= '1';
               last_a(1) <= b_wa;
               ch1_busy  <= '1';
               ch1_fill  <= '1';
               state     <= STATE_START;
            elsif not b_block and a_inflight = '0' and ram_a_wait = '1' then
               we         <= a_rd_n_r;
               bank       <= "00";
               a          <= "00" & a_addr_r;
               data       <= a_di_r & a_di_r;
               ram_req    <= a_fetch_r;
               a_wa       := '0' & a_addr_r(20 downto 2);
               if a_rd_n_r = '1' then
                  last_a(0) <= (others => '1');
                  -- CPU write: invalidate a matching Port B cache line
                  if last_a(1) = a_wa then
                     last_a(1) <= (others => '1');
                  end if;
               else
                  last_a(0) <= a_wa;
               end if;
               ch0_busy   <= '1';
               a_inflight <= '1';
               state      <= STATE_START;
            elsif not b_block and rfsh_cnt = "111111111" then
               rfsh_cnt   <= (others => '0');
               state      <= STATE_START;
            end if;
         end if;

         ---------------------------------------------------------------------------------
         -- Delivery pipeline: latch the access with the READ/WRITE command,
         -- deliver the data CL+2 cycles later
         ---------------------------------------------------------------------------------

         if dl_cnt /= 0 then
            dl_cnt <= dl_cnt - 1;
         end if;

         if state = STATE_CONT and mode = MODE_NORMAL then
            dl_cnt  <= C_DELIVER;
            dl_ch0  <= ch0_busy;
            dl_ch1  <= ch1_busy;
            dl_req  <= ram_req;
            dl_we   <= we;
            dl_a    <= a(1 downto 0);
            dl_data <= data(7 downto 0);
         end if;

         -- store the second word of the burst
         if store(2) = '1' then
            ch := 0;
            if store(1) = '1' then
               ch := 1;
               ch1_fill <= '0';
            end if;
            if store(0) = '1' then
               last_data(ch)(31 downto 16) <= data_reg;
            else
               last_data(ch)(15 downto 0)  <= data_reg;
            end if;
            store <= "000";
         end if;

         if dl_cnt = 1 then
            if dl_req = '0' then
               rfsh_cnt <= (others => '0');
            end if;
            if dl_ch0 = '1' and v_queue then
               -- Another request is queued: start it next, the CPU keeps waiting. Always fetch it
               -- (the cache compare was not done for it).
               a_inflight <= '0';
               a_queued   <= '0';
               a_addr_r   <= v_qaddr;
               a_rd_n_r   <= v_qrd_n;
               a_di_r     <= v_qdi;
               a_fetch_r  <= '1';
               if dl_req = '1' and dl_we = '0' then
                  if dl_a(1) = '1' then
                     last_data(0)(31 downto 16) <= data_reg;
                  else
                     last_data(0)(15 downto 0)  <= data_reg;
                  end if;
                  store <= "1" & "0" & not dl_a(1);
               end if;
            elsif dl_ch0 = '1' then
               v_wait     := '0';
               a_inflight <= '0';
               if dl_req = '1' then
                  if dl_we = '1' then
                     v_do := dl_data;
                  else
                     if dl_a(0) = '1' then
                        v_do := data_reg(15 downto 8);
                     else
                        v_do := data_reg(7 downto 0);
                     end if;
                     if dl_a(1) = '1' then
                        last_data(0)(31 downto 16) <= data_reg;
                     else
                        last_data(0)(15 downto 0)  <= data_reg;
                     end if;
                     store <= "1" & "0" & not dl_a(1);
                  end if;
               else
                  v_do := byte_sel(last_data(0), dl_a);
               end if;
            end if;
            if dl_ch1 = '1' then
               if dl_a(0) = '1' then
                  ram_b_do <= data_reg(15 downto 8);
               else
                  ram_b_do <= data_reg(7 downto 0);
               end if;
               if dl_a(1) = '1' then
                  last_data(1)(31 downto 16) <= data_reg;
               else
                  last_data(1)(15 downto 0)  <= data_reg;
               end if;
               store <= "1" & "1" & not dl_a(1);
            end if;
         end if;

         if rst_i = '1' then
            state      <= STATE_IDLE;
            v_wait     := '0';
            ch0_busy   <= '0';
            ch1_busy   <= '0';
            a_inflight <= '0';
            a_queued   <= '0';
            ch1_fill   <= '0';
            dl_cnt     <= 0;
            store      <= "000";
            l2_timer   <= 0;
            last_a     <= (others => (others => '1'));
         end if;

         ram_a_wait <= v_wait;
         ram_a_do   <= v_do;
         if even then
            a_wait_o <= v_wait;
            a_do_o   <= v_do;
         end if;
      end if;
   end process access_manager;

   ---------------------------------------------------------------------------------------
   -- Initialization
   ---------------------------------------------------------------------------------------

   init : process (clk_i)
   begin
      if rising_edge(clk_i) then
         if por_cnt /= 0 then
            -- 100 us power-up: keep the init sequence at its start
            por_cnt  <= por_cnt - 1;
            init_cnt <= (others => '1');
            mode     <= MODE_RESET;
         elsif state = STATE_LAST then
            if init_cnt /= 0 then
               init_cnt <= init_cnt - 1;
               if init_cnt = 14 then
                  mode <= MODE_PRE;
               elsif init_cnt = 3 then
                  mode <= MODE_LDM;
               else
                  mode <= MODE_RESET;
               end if;
            else
               mode <= MODE_NORMAL;
            end if;
         end if;

         if rst_i = '1' then
            por_cnt  <= C_POR_CYCLES;
            init_cnt <= (others => '1');
            mode     <= MODE_RESET;
         end if;
      end if;
   end process init;

   ---------------------------------------------------------------------------------------
   -- SDRAM commands (all outputs are IOB registers)
   ---------------------------------------------------------------------------------------

   commands : process (clk_i)
   begin
      if rising_edge(clk_i) then
         if state = STATE_START then
            if mode = MODE_NORMAL then
               sd_ba <= bank;
            else
               sd_ba <= "00";
            end if;
         end if;

         cmd     <= CMD_NOP;
         sd_a    <= (others => '0');
         dq_oe_n <= (others => '1');

         if mode = MODE_NORMAL then
            if state = STATE_START then
               if ram_req = '1' then
                  cmd  <= CMD_ACTIVE;
                  sd_a <= a(22 downto 10);
               else
                  cmd  <= CMD_AUTO_REFRESH;
               end if;
            elsif state = STATE_CONT and ram_req = '1' then
               -- A10 = 1: auto precharge; A12/A11 double as DQMH/DQML (write byte mask)
               sd_a <= (we and not a(0)) & (we and a(0)) & "10" & a(9 downto 1);
               if we = '1' then
                  cmd     <= CMD_WRITE;
                  dq_out  <= data;
                  dq_oe_n <= (others => '0');
               else
                  cmd     <= CMD_READ;
               end if;
            end if;
         elsif state = STATE_START then
            case mode is
               when MODE_LDM =>
                  cmd  <= CMD_LOAD_MODE;
                  sd_a <= C_MODE_REG;
               when MODE_PRE =>
                  cmd  <= CMD_PRECHARGE;
                  sd_a <= "0010000000000";      -- precharge all banks
               when others =>
                  -- between PRECHARGE ALL and LOAD MODE: ten auto refresh cycles
                  if por_cnt = 0 and init_cnt >= 3 and init_cnt <= 12 then
                     cmd <= CMD_AUTO_REFRESH;
                  end if;
            end case;
         end if;
      end if;
   end process commands;

   -- DQMH/DQML are the SDRAM_A[12:11] of the MiSTer version; they are separate registers
   -- here so that they can be placed in the IOBs.
   dqm_proc : process (clk_i)
   begin
      if rising_edge(clk_i) then
         sd_dqmh <= '0';
         sd_dqml <= '0';
         if mode = MODE_NORMAL and state = STATE_CONT and ram_req = '1' then
            sd_dqmh <= we and not a(0);
            sd_dqml <= we and a(0);
         end if;
      end if;
   end process dqm_proc;

   sdram_cke_o     <= '1';
   sdram_cs_n_o    <= '0';
   sdram_ras_n_o   <= cmd(2);
   sdram_cas_n_o   <= cmd(1);
   sdram_we_n_o    <= cmd(0);
   sdram_ba_o      <= sd_ba;
   sdram_a_o       <= sd_a;
   sdram_dqmh_o    <= sd_dqmh;
   sdram_dqml_o    <= sd_dqml;
   sdram_dq_out_o  <= dq_out;
   sdram_dq_oe_n_o <= dq_oe_n;

   -- SDRAM clock = inverted controller clock: the SDRAM samples in the middle of our cycle
   i_oddr_clk : ODDR
      generic map (
         DDR_CLK_EDGE => "SAME_EDGE"
      )
      port map (
         D1 => '0',
         D2 => '1',
         CE => '1',
         Q  => sdram_clk_o,
         C  => clk_i,
         R  => '0',
         S  => '0'
      );

end architecture synthesis;
