#!/usr/bin/env python3
# ZX Spectrum Next for MEGA65 (MegaZXNext)
#
# Generates the boot ROM for tb_mouse_reg.vhd (entity bootrom, replaces rtl/rom/bootrom.vhd).
#
# For every value in VALUES the ROM writes nextreg 0x0A (NEXTREG 0x0A,v), then stores v at
# 0xA000 + n. At that store the testbench checks the ZX Next's mouse_control_o, which main.vhd
# uses for the Kempston mouse: bit 2 = button swap (must follow nextreg 0x0A bit 3, which the
# core moved from bit 2 in 3.01.07), bits 1:0 = DPI (nextreg 0x0A bits 1:0).
#
# Usage: mk_mouse_reg_rom.py <output.vhd>
#
# MEGA65 port done by Chris Freeman in 2026 and licensed under GPL v3

import sys

# bit 2 alone must not swap; bit 3 must; the other bits must not leak into mouse_control_o
VALUES = (0x04, 0x08, 0x0B, 0x01, 0x02, 0xF4, 0x0F, 0x00)


def w(v):
    return [v & 0xFF, v >> 8]


rom = [0xF3, 0x31] + w(0xFFF0)                              # DI; LD SP,FFF0
for n, v in enumerate(VALUES):
    rom += [0xED, 0x91, 0x0A, v]                            # NEXTREG 0x0A,v
    rom += [0x3E, v, 0x32] + w(0xA000 + n)                  # LD A,v; LD (A000+n),A
rom += [0x18, 0xFE]                                         # JR $
assert len(rom) <= 8192
rom += [0] * (8192 - len(rom))

lines = ',\n'.join('      ' + ', '.join('x"%02X"' % b for b in rom[i:i + 16]) for i in range(0, 8192, 16))
with open(sys.argv[1], 'w') as f:
    f.write('''-- Generated by mk_mouse_reg_rom.py: test boot ROM for tb_mouse_reg.vhd (%d values)
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity bootrom is
   port (
      CLK  : in  std_logic;
      ADDR : in  std_logic_vector(12 downto 0);
      DATA : out std_logic_vector(7 downto 0)
   );
end entity bootrom;

architecture rtl of bootrom is
   type rom_t is array (0 to 8191) of std_logic_vector(7 downto 0);
   constant ROM : rom_t := (
%s
   );
begin
   process (CLK)
   begin
      if rising_edge(CLK) then
         DATA <= ROM(to_integer(unsigned(ADDR)));
      end if;
   end process;
end architecture rtl;
''' % (len(VALUES), lines))
