#!/usr/bin/env python3
# ZX Spectrum Next for MEGA65 (MegaZXNext)
#
# Generates the boot ROM for tb_cpu_speed.vhd (entity bootrom, replaces rtl/rom/bootrom.vhd).
#
# The ROM copies a test program to 0x8000 (SDRAM) and runs it. The program lowers the CPU speed
# with OUT (C),E to nextreg 0x07, at different phases, for every speed drop, then executes three
# INC HL and stores L at 0xA000 + n. Every stored byte must be 3: a lost opcode fetch right after
# the speed change (the R6 bug fixed in zxnext_top_m65.vhd) stores 1 or 2.
#
# Usage: mk_cpu_speed_rom.py <output.vhd>
#
# MEGA65 port done by Chris Freeman in 2026 and licensed under GPL v3

import sys

ORG = 0x8000
DROPS = ((3, 0), (3, 1), (3, 2), (2, 0), (1, 0), (2, 1))   # (from, to): 0 = 3.5 MHz .. 3 = 28 MHz
PHASES = 8
RESULTS = len(DROPS) * PHASES


def w(v):
    return [v & 0xFF, v >> 8]


p = []
p += [0xF3, 0x31] + w(0xFFF0)                               # DI; LD SP,FFF0
p += [0x01] + w(0x243B) + [0x3E, 0x07, 0xED, 0x79, 0x04]    # LD BC,243B; LD A,7; OUT (C),A; INC B
p += [0xDD, 0x21] + w(0xA000)                               # LD IX,A000
n = 0
for (fr, to) in DROPS:
    for k in range(PHASES):
        p += [0xED, 0x91, 0x07, fr]                         # NEXTREG 7,from
        p += [0x00] * (4 + k)                               # NOPs: vary the phase of the switch
        p += [0x1E, to, 0x21] + w(0)                        # LD E,to; LD HL,0
        p += [0xED, 0x59]                                   # OUT (C),E: nextreg 7 = to
        p += [0x23, 0x23, 0x23]                             # INC HL (3x)
        p += [0x7D, 0xDD, 0x77, n]                          # LD A,L; LD (IX+n),A
        n += 1
p += [0x18, 0xFE]                                           # JR $

# boot ROM: 28 MHz, copy the program to ORG and jump there
loader = [0xF3, 0xED, 0x91, 0x07, 0x03, 0x21] + w(0) + [0x11] + w(ORG) + [0x01] + w(len(p)) + \
         [0xED, 0xB0, 0xC3] + w(ORG)
loader[6:8] = w(len(loader))
rom = loader + p
assert len(rom) <= 8192
rom += [0] * (8192 - len(rom))

lines = ',\n'.join('      ' + ', '.join('x"%02X"' % b for b in rom[i:i + 16]) for i in range(0, 8192, 16))
with open(sys.argv[1], 'w') as f:
    f.write('''-- Generated by mk_cpu_speed_rom.py: test boot ROM for tb_cpu_speed.vhd (%d results)
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity bootrom is
   port (
      CLK  : in  std_logic;
      ADDR : in  std_logic_vector(12 downto 0);
      DATA : out std_logic_vector(7 downto 0)
   );
end entity bootrom;

architecture rtl of bootrom is
   type rom_t is array (0 to 8191) of std_logic_vector(7 downto 0);
   constant ROM : rom_t := (
%s
   );
begin
   process (CLK)
   begin
      if rising_edge(CLK) then
         DATA <= ROM(to_integer(unsigned(ADDR)));
      end if;
   end process;
end architecture rtl;
''' % (RESULTS, lines))
